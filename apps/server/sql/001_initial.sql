CREATE TABLE IF NOT EXISTS users (
  id text PRIMARY KEY,
  name text NOT NULL,
  role text NOT NULL CHECK (role IN ('client', 'staff')),
  username text UNIQUE,
  password_hash text,
  CHECK ((username IS NULL) = (password_hash IS NULL))
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  user_id text NOT NULL REFERENCES users(id),
  expires_at timestamptz NOT NULL,
  browser boolean NOT NULL
);
CREATE TABLE IF NOT EXISTS salons (
  id text PRIMARY KEY,
  data jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS services (
  id text PRIMARY KEY,
  salon_id text NOT NULL REFERENCES salons(id),
  data jsonb NOT NULL,
  UNIQUE (id, salon_id)
);
CREATE TABLE IF NOT EXISTS barbers (
  id text PRIMARY KEY,
  salon_id text NOT NULL REFERENCES salons(id),
  data jsonb NOT NULL,
  availability text NOT NULL CHECK (availability IN ('working', 'paused', 'away')),
  UNIQUE (id, salon_id)
);
CREATE TABLE IF NOT EXISTS queue_entries (
  id text PRIMARY KEY,
  salon_id text NOT NULL REFERENCES salons(id),
  client_id text NOT NULL REFERENCES users(id),
  service_id text NOT NULL,
  joined_at timestamptz NOT NULL,
  sequence integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) UNIQUE,
  status text NOT NULL CHECK (status IN ('waiting','called','inProgress','completed','cancelled','noShow')),
  barber_id text,
  note text NOT NULL,
  revision integer NOT NULL CHECK (revision >= 0),
  FOREIGN KEY (service_id, salon_id) REFERENCES services(id, salon_id),
  FOREIGN KEY (barber_id, salon_id) REFERENCES barbers(id, salon_id),
  CHECK (status NOT IN ('called', 'inProgress') OR barber_id IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_entry_per_salon
  ON queue_entries (client_id, salon_id) WHERE status IN ('waiting','called','inProgress');
CREATE UNIQUE INDEX IF NOT EXISTS one_active_entry_per_barber
  ON queue_entries (barber_id) WHERE status IN ('called','inProgress');
